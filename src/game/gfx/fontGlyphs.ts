/** Characters in atlas order (ASCII 32..126). */
export const FONT_CHARS: string = Array.from({ length: FONT_LAST - FONT_FIRST + 1 }, (_, i) =>
  String.fromCharCode(FONT_FIRST + i),
).join("");

/** Glyph rows (7 values of 5 bits) for a character; space for unknown chars. */
export function glyphRows(ch: string): readonly number[] {
  return G[ch] ?? G[" "];
}

/** True if the glyph table defines the character. */
export function hasGlyph(ch: string): boolean {
  return Object.prototype.hasOwnProperty.call(G, ch);
}

/** Atlas size in pixels. */
export function fontAtlasSize(): { w: number; h: number } {
  const rows = Math.ceil(FONT_CHARS.length / CHARS_PER_ROW);
  return { w: CHARS_PER_ROW * CELL_W, h: rows * CELL_H };
}

/** Lit pixels of the atlas as [x, y] pairs. */
export function fontAtlasPixels(): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (let i = 0; i < FONT_CHARS.length; i++) {
    const cx = (i % CHARS_PER_ROW) * CELL_W;
    const cy = Math.floor(i / CHARS_PER_ROW) * CELL_H;
    const rows = glyphRows(FONT_CHARS[i]);
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (rows[r] & (1 << (GLYPH_W - 1 - c))) out.push([cx + c, cy + r]);
      }
    }
  }
  return out;
}
